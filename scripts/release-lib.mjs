import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { readdir, lstat, mkdir, copyFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

// Deliberately accept only the documented release channels; also safe in filenames/Ruby.
const versionPattern =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-(alpha|beta|rc)\.(0|[1-9]\d*))?$/;
async function fileHash(file) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(file)) hash.update(chunk);
  return hash.digest('hex');
}
export function releaseVersion(tag, version) {
  if (!versionPattern.test(version) || tag !== `v${version}`)
    throw new Error('Tag must match package.json: vX.Y.Z or vX.Y.Z-(alpha|beta|rc).N.');
  return { version, prerelease: version.includes('-') };
}

export function artifactNames(version) {
  releaseVersion(`v${version}`, version);
  return [
    ...['arm64', 'x64'].flatMap((arch) => [
      `Sim-Relay-${version}-mac-${arch}.dmg`,
      `Sim-Relay-${version}-mac-${arch}.zip`,
      // electron-builder uses AppImage's conventional x86_64 spelling for x64.
      `Sim-Relay-${version}-linux-${arch === 'x64' ? 'x86_64' : arch}.AppImage`,
      `Sim-Relay-${version}-linux-${arch}.tar.gz`,
      `Sim-Relay-${version}-linux-${arch === 'x64' ? 'amd64' : arch}.deb`,
      `Sim-Relay-${version}-linux-${arch === 'x64' ? 'x86_64' : 'aarch64'}.rpm`,
      `Sim-Relay-${version}-windows-${arch}.exe`,
    ]),
  ].sort();
}

export function homebrewCask(version, hashes, repository) {
  if (releaseVersion(`v${version}`, version).prerelease)
    throw new Error('Only stable releases can update Homebrew.');
  if (!/^[\w-]+\/[\w.-]+$/.test(repository)) throw new Error('Invalid repository.');
  const hash = (arch) => {
    const result = hashes[`Sim-Relay-${version}-mac-${arch}.dmg`];
    if (!/^[a-f0-9]{64}$/.test(result ?? '')) throw new Error(`Missing ${arch} DMG checksum.`);
    return result;
  };
  return `# Generated by the release workflow. Do not edit checksums manually.
cask "sim-relay" do
  arch arm: "arm64", intel: "x64"

  version "${version}"
  sha256 arm:   "${hash('arm64')}",
         intel: "${hash('x64')}"

  url "https://github.com/${repository}/releases/download/v#{version}/Sim-Relay-#{version}-mac-#{arch}.dmg"
  name "Sim Relay"
  desc "Use iOS simulators on another Mac"
  homepage "https://github.com/${repository}"

  depends_on macos: :ventura

  app "Sim Relay.app"
  binary "#{appdir}/Sim Relay.app/Contents/Resources/bin/sim-relay-host"

  uninstall launchctl: "dev.simrelay.host"

  zap trash: [
    "~/Library/Application Support/Sim Relay",
    "~/Library/Application Support/ios-sim-stream",
    "~/Library/Logs/Sim Relay",
  ]
end
`;
}

export async function assembleRelease({
  input,
  output,
  version,
  repository,
  macSigned,
  windowsSigned,
}) {
  const { prerelease } = releaseVersion(`v${version}`, version);
  const expected = artifactNames(version);
  const actual = (await readdir(input)).sort();
  if (JSON.stringify(actual) !== JSON.stringify(expected))
    throw new Error(
      `Release assets must exactly match all six targets. Expected: ${expected.join(', ')}; got: ${actual.join(', ')}`,
    );
  await mkdir(output, { recursive: true });
  if ((await readdir(output)).length) throw new Error('Release output directory must be empty.');
  const hashes = {};
  for (const name of expected) {
    const file = path.join(input, name);
    const info = await lstat(file);
    if (!info.isFile() || info.size === 0) throw new Error(`Not a nonempty regular file: ${name}`);
    hashes[name] = await fileHash(file);
    await copyFile(file, path.join(output, name));
  }
  await writeFile(
    path.join(output, 'release.json'),
    JSON.stringify(
      {
        version,
        repository,
        macSignedAndNotarized: macSigned,
        windowsSigned,
        assets: expected.map((name) => ({ name, sha256: hashes[name] })),
      },
      null,
      2,
    ) + '\n',
  );
  if (!prerelease)
    await writeFile(path.join(output, 'sim-relay.rb'), homebrewCask(version, hashes, repository));
  const files = (await readdir(output)).sort();
  const sums = await Promise.all(
    files.map(async (name) => `${await fileHash(path.join(output, name))}  ${name}\n`),
  );
  await writeFile(path.join(output, 'SHA256SUMS'), sums.join(''));
  return (
    [
      'Installers: macOS arm64/x64 (DMG and ZIP), Windows arm64/x64 (EXE), Linux arm64/x64 (AppImage, tar.gz, DEB, and RPM).',
      `macOS: ${macSigned ? 'Developer ID signed and notarized.' : 'ad-hoc signed; not notarized. See the macOS installation guide before opening.'}`,
      `Windows: ${windowsSigned ? 'certificate signed.' : 'unsigned; Windows may display a publisher warning.'}`,
      `Installation and Mac host setup: https://github.com/${repository}/blob/v${version}/docs/macos.md`,
      'SHA256SUMS covers every attached installer and metadata file. The app does not auto-update; install a newer release or use brew upgrade.',
    ].join('\n\n') + '\n'
  );
}

export function shouldUpdateCask(existing, incoming) {
  const getVersion = (text) => {
    const version = text.match(/^  version "([^"]+)"$/m)?.[1];
    if (!version || releaseVersion(`v${version}`, version).prerelease)
      throw new Error('Expected a generated stable Homebrew cask.');
    return version.split('.').map(BigInt);
  };
  const next = getVersion(incoming);
  if (!existing) return true;
  const current = getVersion(existing);
  for (let i = 0; i < 3; i++) {
    if (next[i] !== current[i]) return next[i] > current[i];
  }
  return false; // Re-runs never replace an already released version's checksum.
}
